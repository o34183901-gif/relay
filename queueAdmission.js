/**
 * queueAdmission.js — пускать ли конверт в очередь получателя и кого вытеснить
 * (ВЫС-15). Чистое правило, без базы.
 *
 * ЧТО БЫЛО НЕ ТАК
 *
 * Квота на пару «отправитель→получатель» (S5) защищает от ОДНОГО флудера: свой
 * потолок он выбирает и дальше ротирует собственный спам. Но личности
 * бесплатны. Пять свежих ключей по MAX_QUEUE_PER_SENDER=100 конвертов выбирают
 * MAX_QUEUE_PER_USER=500 целиком — и очередь жертвы закрыта наглухо: честный
 * отправитель, у которого в ней нет своих конвертов, получает drop-new. Спам
 * лежит до TTL, то есть жертва не получает новых сообщений ЧЕТЫРНАДЦАТЬ СУТОК,
 * и ни она, ни отправители об этом не знают ничего.
 *
 * ЧТО ЗДЕСЬ
 *
 * Два дополнения к прежним правилам, оба вокруг одного факта: НЕЗНАКОМЦУ у
 * чужой очереди места меньше, чем тому, кому получатель сам писал.
 *
 *   • РЕЗЕРВ. Незнакомцы все вместе занимают не больше maxPerUser - reserve
 *     слотов. Последние reserve слотов доступны только корреспондентам —
 *     отправителям, которым получатель сам недавно писал. Сколько бы личностей
 *     ни завёл флудер, все они незнакомцы, и резерв им не достаётся.
 *   • ВЫТЕСНЕНИЕ ЧУЖОГО СПАМА. Корреспондент, упёршийся в полную очередь без
 *     собственных конвертов в ней, вытесняет старейший конверт НЕЗНАКОМЦА.
 *     Раньше ему отвечали drop-new — то есть спам был неприкосновенен, а
 *     настоящее письмо отбрасывалось.
 *
 * Кто такой «корреспондент», решает сам получатель — фактом своей отправки:
 * узел помнит непрозрачные метки пар, по которым НЕДАВНО проходили конверты
 * (та же метка, что в квотах: HMAC, ключей в ней не видно). Писал B→S — значит
 * S для B корреспондент. Личности флудера этого свойства не получают никогда:
 * жертва им не пишет.
 *
 * Чего это НЕ ломает. Первое сообщение незнакомца проходит как раньше —
 * незнакомцам закрыт только резерв, а не очередь. Знакомство двух людей не
 * требует, чтобы кто-то был «корреспондентом»: до резерва очередь общая.
 *
 * Проверяется в server/queueAdmission.test.js.
 */

'use strict';

/**
 * Сколько слотов очереди получателя доступно ТОЛЬКО корреспондентам.
 * Пятая часть от пятисот: сто конвертов — заведомо больше, чем честные
 * собеседники держат недоставленным одновременно.
 */
const QUEUE_RESERVE = 100;

/**
 * Решение о приёме конверта.
 *
 *   recipientCount — сколько конвертов в очереди получателя всего;
 *   strangerCount  — из них от незнакомцев;
 *   senderCount    — сколько уже держит ЭТОТ отправитель у ЭТОГО получателя;
 *   correspondent  — писал ли получатель этому отправителю недавно;
 *   senderKnown    — известен ли отправитель вовсе (легаси-кадры без from);
 *
 * Возвращает { admit, evict }:
 *   admit — принимать ли конверт;
 *   evict — кого вытеснить перед приёмом: 'own' (свой старейший этой пары),
 *           'stranger' (старейший конверт незнакомца), 'oldest' (старейший
 *           получателя — только легаси без отправителя), null — никого.
 */
function admitEnvelope({
  recipientCount = 0,
  strangerCount = 0,
  senderCount = 0,
  correspondent = false,
  senderKnown = true,
  maxPerUser = 0,
  maxPerSender = 0,
  reserve = QUEUE_RESERVE,
} = {}) {
  // S5: свой потолок пары — вытесняется свой же старейший. Для всех одинаково:
  // и корреспондент не может занять чужую очередь целиком.
  if (maxPerSender && senderKnown && senderCount >= maxPerSender) {
    return { admit: true, evict: 'own' };
  }
  if (!maxPerUser || recipientCount < maxPerUser) {
    // Очередь не полна. Незнакомец при этом не заходит в резерв: сколько бы
    // личностей ни было у флудера, последние reserve слотов им не достаются.
    // Без потолка очереди нет и резерва — резервировать не от чего.
    if (
      maxPerUser > 0 &&
      reserve > 0 &&
      senderKnown &&
      !correspondent &&
      strangerCount >= Math.max(0, maxPerUser - reserve)
    ) {
      return { admit: false, evict: null };
    }
    return { admit: true, evict: null };
  }
  // Очередь полна.
  if (!senderKnown) {
    // Легаси без отправителя: некому атрибутировать — прежнее поведение.
    return { admit: true, evict: 'oldest' };
  }
  if (senderCount > 0) {
    // Свои конверты есть — ротируем свой старейший, чужие неприкосновенны.
    return { admit: true, evict: 'own' };
  }
  if (correspondent && strangerCount > 0) {
    // ВЫС-15: настоящее письмо не отбрасывается ради лежащего спама. Резерв
    // выбран незнакомцами — корреспондент вытесняет старейший ИХ конверт.
    return { admit: true, evict: 'stranger' };
  }
  // Незнакомец у полной очереди (или корреспондент у очереди, полной письмами
  // других корреспондентов): drop-new — уже принятые сообщения неприкосновенны.
  return { admit: false, evict: null };
}

module.exports = {
  QUEUE_RESERVE,
  admitEnvelope,
};
