/**
 * x25519.js — общий секрет, с одинаковым поведением у всех реализаций (НАТ-2).
 *
 * ЗАЧЕМ ЭТО ОТДЕЛЬНЫЙ МОДУЛЬ
 *
 * Не ради скорости. Ради того, что три реализации X25519 ведут себя ПО-РАЗНОМУ
 * на враждебном входе, а входы здесь именно враждебные: чужой открытый ключ
 * приезжает из сети.
 *
 * Точка малого порядка даёт общий секрет, не зависящий от секретки, — это и
 * есть способ подсунуть сообщение от поддельного ключа (КЛТ-4). Замерено на
 * шести известных точках малого порядка:
 *
 *   tweetnacl       возвращает НУЛИ и ничего не сообщает
 *   @noble/curves   бросает «invalid private or public key»
 *   OpenSSL         бросает «Provider routines::failed»
 *
 * Проверка на нули, написанная под tweetnacl, у двух других не выполнится
 * никогда: до неё не дойдёт. Наоборот, код, который ловит исключение и считает
 * это отказом, при tweetnacl молча получит нулевой секрет и пойдёт дальше.
 * Пока реализация одна, это незаметно; в день замены — это дыра, и найти её
 * будет нечем, потому что все тесты зелёные.
 *
 * Поэтому здесь одно поведение для всех: вырожденная точка — это `Error` с
 * одним и тем же сообщением, откуда бы она ни пришла. Проверка на нули
 * остаётся и для тех реализаций, которые бросают сами: она ничего не стоит и
 * не полагается на то, что нижний слой не передумает.
 *
 * ЧТО С ЭТОГО ПО СКОРОСТИ
 *
 * Замер одного общего секрета:
 *
 *   @noble/curves   0,920 мс
 *   tweetnacl       0,646 мс
 *   OpenSSL         0,035 мс
 *
 * Важное здесь — средняя строка. @noble/curves на X25519 МЕДЛЕННЕЕ tweetnacl,
 * хотя на подписи он же быстрее в десять раз. Перевести сюда noble «заодно с
 * подписью» — распространённая мысль, и она сделала бы хуже. Это записано
 * тестом, а не только на словах.
 *
 * OpenSSL быстрее tweetnacl в восемнадцать раз, но он есть не везде — поэтому
 * приходит снаружи через `setNative`, как и у подписи (НАТ-1).
 *
 * Модуль чистый. Тест — test/x25519.test.js.
 */
'use strict';

const nacl = require('tweetnacl');

/** Длина и ключа, и общего секрета. */
const KEY_LENGTH = 32;

/**
 * Одно сообщение на всех.
 *
 * Ловящая сторона сравнивает именно с ним — и потому не зависит от того, какая
 * реализация стоит внизу и как она называет свою ошибку.
 */
const LOW_ORDER_MESSAGE = 'low-order DH point';

/** Все нули? Постоянное время: ветвления по содержимому секрета здесь не место. */
function isZero(bytes) {
  let acc = 0;
  for (let i = 0; i < bytes.length; i += 1) acc |= bytes[i];
  return acc === 0;
}

/**
 * НАТ-4: ВТОРОЙ РУБЕЖ — проверка уже готового парного секрета.
 *
 * ЗАЧЕМ ОН НУЖЕН, ЕСЛИ ЕСТЬ ПЕРВЫЙ
 *
 * `sharedSecret` выше закрывает вырожденную точку в момент счёта. Но парный
 * секрет живёт дольше вызова: он кэшируется (relay.meshPairCache), приезжает
 * из состояния, записанного прежней версией приложения, и передаётся между
 * модулями обычным Uint8Array. Рубеж на входе не заменяет рубеж на выходе —
 * они закрывают разные пути появления одного и того же нуля.
 *
 * Это не теория: до НАТ-4 первого рубежа в парном секрете не было вовсе
 * (lanBeacon.pairSecret считал прямым вызовом tweetnacl), и единственное, что
 * тогда спасло точки встречи, — как раз этот второй рубеж, живший там своей
 * копией. Теперь копия одна на проект, и ею пользуются все, кто выводит метки
 * из парного секрета: точки встречи, маяк общей сети, передача через соседей.
 *
 * ПОЧЕМУ ЗДЕСЬ, А НЕ В КАЖДОМ ИЗ НИХ
 *
 * Ровно по той же причине, по которой здесь живёт сам общий секрет: три копии
 * одной проверки расходятся, и разошедшуюся не видно, пока не станет поздно.
 *
 * Сообщения оставлены прежними побайтно — их закрепляют тесты точек встречи, и
 * менять текст отказа заодно с переездом означало бы смешать две правки.
 */
const NO_PAIR_SECRET_MESSAGE = 'Нет общего секрета пары';
const DEGENERATE_SECRET_MESSAGE = 'Вырожденный общий секрет: публичный ключ контакта негоден';

function assertPairSecret(secret) {
  if (!(secret instanceof Uint8Array) || secret.length !== KEY_LENGTH) {
    throw new Error(NO_PAIR_SECRET_MESSAGE);
  }
  if (isZero(secret)) throw new Error(DEGENERATE_SECRET_MESSAGE);
  return secret;
}

function createX25519() {
  // НАТ-2: уровень OpenSSL. Вносится снаружи и только после самопроверки —
  // см. src/nativeX25519.js.
  let native = null;

  /** Внесён ли уровень OpenSSL — для диагностики и тестов. */
  function nativeAvailable() {
    return !!native;
  }

  /**
   * Внести реализацию поверх OpenSSL. `null` снимает уровень обратно.
   *
   * Как и у подписи, собственной проверки здесь нет: вносит только тот, кто
   * проверил. Это стережётся проверкой связки, а не условием в коде.
   */
  function setNative(next) {
    if (next === null || next === undefined) {
      native = null;
      return false;
    }
    if (typeof next.sharedSecret !== 'function') {
      throw new Error('setNative: реализация обязана иметь sharedSecret');
    }
    native = next;
    return true;
  }

  /**
   * Общий секрет.
   *
   * Бросает `Error(LOW_ORDER_MESSAGE)` на вырожденной точке — одинаково при
   * любой реализации внизу. Ключ не той длины считается тем же случаем: короткий
   * ключ у OpenSSL дополнился бы нулями до другого законного ключа, а у
   * tweetnacl прочитался бы с чужой памятью за концом.
   */
  function sharedSecret(secretKey, publicKey) {
    if (!secretKey || secretKey.length !== KEY_LENGTH) throw new Error(LOW_ORDER_MESSAGE);
    if (!publicKey || publicKey.length !== KEY_LENGTH) throw new Error(LOW_ORDER_MESSAGE);

    let out;
    if (native) {
      try {
        out = native.sharedSecret(secretKey, publicKey);
      } catch (error) {
        // OpenSSL отвергает вырожденную точку сам — приводим его отказ к общему
        // виду, иначе вызывающий обязан был бы знать, какая реализация внизу.
        throw new Error(LOW_ORDER_MESSAGE);
      }
    } else {
      out = nacl.scalarMult(secretKey, publicKey);
    }

    // Проверка остаётся и для тех, кто бросает сам: она ничего не стоит и не
    // полагается на то, что нижний слой не передумает.
    if (!out || out.length !== KEY_LENGTH || isZero(out)) throw new Error(LOW_ORDER_MESSAGE);
    return out;
  }

  /**
   * НАТ-4: НУЛЕВОЙ РУБЕЖ — годится ли чужой открытый ключ вообще.
   *
   * Спрашивается ОДИН раз, в момент, когда ключ впервые попадает к нам: при
   * разборе кода знакомства. Дальше он лежит в адресной книге и расходится по
   * всем путям сразу, поэтому отсеивать его надо здесь, а не в каждом из них.
   *
   * ПОЧЕМУ ПРОБА, А НЕ СПИСОК ИЗВЕСТНЫХ ТОЧЕК
   *
   * Список пришлось бы поддерживать, а забытая в нём точка выглядела бы как
   * рабочая проверка. Проба отвечает на нужный вопрос напрямую: после
   * приведения скаляр X25519 всегда кратен восьми, поэтому точка малого порядка
   * даёт нулевой результат при ЛЮБОМ скаляре — детерминированно, а не с
   * вероятностью. Так же устроена проверка в libsodium.
   *
   * Скаляр случайный, а не постоянный: постоянный превратил бы пробу в сравнение
   * с одним заранее известным значением — стоило бы столько же, а проверяло бы
   * меньше.
   *
   * Бросает тот же `LOW_ORDER_MESSAGE`, что и сам общий секрет: ответ на «эта
   * точка не годится» обязан быть один, откуда бы вопрос ни пришёл.
   */
  function assertUsableKey(publicKey) {
    sharedSecret(nacl.randomBytes(KEY_LENGTH), publicKey);
    return publicKey;
  }

  return { sharedSecret, assertUsableKey, nativeAvailable, setNative };
}

const { sharedSecret, assertUsableKey, nativeAvailable, setNative } = createX25519();

module.exports = {
  KEY_LENGTH,
  LOW_ORDER_MESSAGE,
  NO_PAIR_SECRET_MESSAGE,
  DEGENERATE_SECRET_MESSAGE,
  assertPairSecret,
  assertUsableKey,
  sharedSecret,
  nativeAvailable,
  setNative,
  createX25519,
};
