/**
 * envelopeFrame.js — обычное сообщение едет по проводу ДВОИЧНЫМ кадром (ПРФ-14).
 *
 * ЧТО БЫЛО НЕ ТАК
 *
 * Конверт уже давно непрозрачный блоб: sealedSender.seal отдаёт
 * `{ v, sealed }`, где `sealed` — это base64 от байтов. Байты превращались в
 * base64 (+33% на сам блоб), строка вставлялась в JSON-кадр `send`, и всё это
 * при том, что двоичный транспорт в проекте УЖЕ есть и работает: чанки вложений
 * ходят кадром LICNOBA1 (server/binary-frame.js) без всякого base64.
 *
 * Замер по настоящему пути отправки (типичная реплика, после набивки
 * src/padding.js): кадр `send` в JSON — 871 байт, тот же кадр двоично — 663.
 * Раздувание +31.4%, экономия −23.9%.
 *
 * Число надо называть честно: это НЕ «сильно больше +33%», а немного меньше.
 * Ровно +33.8% ложится только на само тело конверта (529 байт → 708 символов
 * base64); остальные 163 байта кадра — `to`, `ref`, тип и флаги — в base64 не
 * кодируются и потому не раздуваются вовсе. Экранирования тоже нет ни одного:
 * алфавит base64 (`A–Z a–z 0–9 + / =`) не содержит ни единого символа, который
 * JSON обязан экранировать, так что «JSON-строка с экранированием» здесь ничего
 * не стоила. Доля выигрыша растёт с размером сообщения (на кадре в 4 КБ —
 * −24.9%), потому что постоянная открытая часть размывается.
 *
 * ЧТО МОЖНО ПЕРЕВОДИТЬ В ДВОИЧНЫЙ КАДР, А ЧТО НЕЛЬЗЯ
 *
 * Только ЗАПЕЧАТАННЫЙ конверт, то есть ровно `{ v, sealed }`. Это не
 * перестраховка, а граница приватности, и она здесь главное.
 *
 * Заголовок двоичного кадра — открытый текст (см. binary-frame.js: он лежит до
 * тела и не шифруется ничем). Незапечатанный конверт Double Ratchet — это
 * `{ v, dr, from, header: { dh, n, pn }, nonce, cipher, x3dh? }`. Разложи мы ЕГО
 * по полям заголовка ради тех же байтов — наружу вышли бы публичный ключ
 * отправителя, эфемерный ключ храповика, счётчики цепочки и признак первого
 * контакта, то есть ровно то, что К-1б (sealedSender) закрыл. Поэтому такой
 * конверт продолжает ехать прежним JSON-кадром целиком, а двоичный путь его
 * молча не принимает: `sealedBytes` возвращает null, и вызывающий обязан отдать
 * JSON.
 *
 * Из этого же следует состав открытой части двоичного кадра: в ней НЕТ ничего,
 * чего не было в JSON-кадре. Ни адреса отправителя, ни длины, ни признаков —
 * сверка списков полей вынесена в тест (test/envelopeFrame.test.js), чтобы
 * новое поле нельзя было добавить незаметно.
 *
 * С КЕМ СОГЛАСУЕТСЯ ПЕРЕХОД — И ПОЧЕМУ НЕ С КОНТАКТОМ
 *
 * Возможность объявляется РЕЛЕЮ (в кадре `hello`), а не собеседнику. Это
 * отличается от всех прежних переходов проекта — `padded-attachments-v1`,
 * `native-chunk-crypto-v1` и прочих, которые хранятся в белом списке
 * setContactCapabilities, — и отличие не случайное.
 *
 * Там согласовывать НАДО с контактом: чанк вложения релей пересылает БАЙТ В
 * БАЙТ, поэтому формат выбирает отправитель, и ошибиться в чужих способностях
 * значит не доставить файл.
 *
 * Здесь пересылки байт в байт нет. Релей разбирает кадр, собирает конверт
 * обратно в `{ v, sealed }` и кладёт его в очередь JSON-ом (store не тронут), а
 * при выдаче заново решает, каким кадром отдать — по возможностям ТОГО
 * СОЕДИНЕНИЯ, которое забирает. Формат участка «отправитель → релей» и участка
 * «релей → получатель» независимы. Значит отправителю знать о клиенте
 * получателя нечего, а запись в белом списке контактов никто бы не читал.
 *
 * Проверяется это прямо: в server/test.js отправитель шлёт двоичный кадр, а
 * получатель прежней версии, не объявивший НИЧЕГО, принимает обычный JSON-кадр
 * с тем же конвертом.
 *
 * ПОЧЕМУ ПРАВИЛО ЖИВЁТ ОТДЕЛЬНЫМ МОДУЛЕМ И ОДНО НА ОБЕ СТОРОНЫ
 *
 * Клиент решает, что можно упаковать; релей решает, что он готов распаковать и
 * что отдать обратно. Разойдись эти два решения хоть на условие — и получится
 * либо потерянное сообщение (релей не понял кадр), либо утечка (в заголовок
 * попало поле, которое обязано было остаться внутри шифра). Поэтому файл
 * генерируется в server/envelopeFrame.js скриптом scripts/sync-core.js: разойтись
 * копии не могут, `npm run core:check` этого не пропустит.
 *
 * Модуль чистый: ни сети, ни хранилища, ни платформы.
 */

const { decodeBase64, encodeBase64 } = require('tweetnacl-util');

/** Возможность: сторона умеет принимать обычное сообщение двоичным кадром. */
const BINARY_ENVELOPE_CAPABILITY = 'binary-envelope-v1';

/** Тип кадра «отправить конверт» (клиент → релей). */
const SEND_FRAME_TYPE = 'send-v1';

/** Тип кадра «вот конверт» (релей → получатель). */
const MESSAGE_FRAME_TYPE = 'message-v1';

/**
 * Версия внешнего запечатанного слоя, которую этот формат умеет переносить.
 * Совпадает с sealedSender.SEALED_VERSION и проверяется явно: появись версия 2 с
 * другим разбором блоба, старый релей не должен молча выдать её за первую.
 */
const SEALED_ENVELOPE_VERSION = 1;

/**
 * Накладные расходы конверта в JSON: `{"v":1,"sealed":""}` плюс запас на
 * многозначную версию. Нужны, чтобы проверять размер тела ДО кодирования —
 * иначе кадр на 33 МБ сначала превратился бы в 44 МБ base64 и только потом был
 * отвергнут по потолку конверта.
 */
const ENVELOPE_JSON_OVERHEAD = 32;

/**
 * Сколько байт тела допустимо, чтобы конверт уложился в `maxEnvelopeJsonBytes`
 * после кодирования в base64.
 */
function maxSealedBytes(maxEnvelopeJsonBytes) {
  const room = maxEnvelopeJsonBytes - ENVELOPE_JSON_OVERHEAD;
  if (!(room > 0)) return 0;
  return Math.floor(room / 4) * 3;
}

/**
 * Байты запечатанного конверта — либо null, если этот конверт двоично гнать
 * НЕЛЬЗЯ.
 *
 * Требования строгие и все обязательные:
 *   • ровно два поля, `v` и `sealed`, и ничего сверх — лишнее поле при упаковке
 *     потерялось бы молча, а конверт у получателя перестал бы совпадать с
 *     отправленным;
 *   • известная версия внешнего слоя;
 *   • `sealed` — КАНОНИЧЕСКИЙ base64, то есть переживающий обратное кодирование
 *     байт в байт. Иначе распаковка вернула бы строку, отличную от исходной, и
 *     сравнение конвертов (дедуп, тесты, диагностика) начало бы врать.
 */
function sealedBytes(envelope) {
  if (!envelope || typeof envelope !== 'object' || Array.isArray(envelope)) return null;
  const keys = Object.keys(envelope);
  if (keys.length !== 2 || !keys.includes('v') || !keys.includes('sealed')) return null;
  if (envelope.v !== SEALED_ENVELOPE_VERSION) return null;
  if (typeof envelope.sealed !== 'string' || !envelope.sealed) return null;
  let bytes;
  try {
    bytes = decodeBase64(envelope.sealed);
  } catch (error) {
    return null;
  }
  if (!bytes.length) return null;
  if (encodeBase64(bytes) !== envelope.sealed) return null;
  return bytes;
}

/**
 * Обратное преобразование: собрать конверт из версии и тела кадра.
 * null — версия чужая или тело пустое; вызывающий тогда просто игнорирует кадр.
 */
function sealedEnvelope(version, bytes) {
  if (version !== SEALED_ENVELOPE_VERSION) return null;
  if (!(bytes instanceof Uint8Array) || !bytes.length) return null;
  return { v: SEALED_ENVELOPE_VERSION, sealed: encodeBase64(bytes) };
}

/**
 * Заголовок кадра отправки (клиент → релей).
 *
 * Больше в заголовке нет ничего. `sv` — версия внешнего слоя, та самая, что
 * ехала полем `envelope.v` открытым текстом и раньше.
 *
 * СРЕД-01: ДЛИНА ЗАГОЛОВКА НЕ ЗАВИСИТ ОТ ЗНАЧЕНИЯ ФЛАГОВ
 *
 * Что было не так. `silent` и `callPush` выписывались, только когда они ИСТИНА,
 * ради 32 сэкономленных байт. Значения при этом не терялись — отсутствие поля
 * читается как `false` ровно так же, как в JSON-кадре, — а вот ДЛИНА кадра
 * начинала их кодировать: `,"silent":true` занимает ровно 14 байт,
 * `,"callPush":true` — 16. Четыре сочетания флагов давали четыре разные длины,
 * и различаются они, не прочитав из кадра ни байта: релею заголовок открыт и
 * так, а стороннему наблюдателю видна длина TLS-записи.
 *
 * Экономия покупалась ровно тем, что мессенджер закрывает в соседнем месте:
 * набивка (src/padding.js) уравнивает по размеру короткую реплику и служебную
 * квитанцию, а флаг, проступивший в длине кадра, тут же их разделял. `silent`
 * стоит именно на служебном потоке (квитанции о прочтении, «печатает…»,
 * анонсы) и на копиях веера, `callPush` — на звонке. Прежний JSON-путь такой
 * разницы не давал вовсе: buildSendFrame в src/relay.js выписывает оба флага
 * ВСЕГДА, поэтому по длине кадра `send` они не читались никогда, и утечку внёс
 * именно переход на двоичный кадр.
 *
 * Что теперь. Оба флага выписываются всегда и ЦИФРОЙ — `0` либо `1`. Запись
 * занимает одинаковое число байт при любом значении, поэтому при равных `to` и
 * `ref` все четыре сочетания дают кадр побайтно одной длины (проверяется в
 * test/envelopeFrame.test.js).
 *
 * Почему цифра, а не `true`/`false`: булево пишется четырьмя и пятью символами,
 * то есть это та же утечка, просто в один байт. Один байт разницы читается
 * ничуть не хуже четырнадцати.
 *
 * Почему не одно поле-битовая маска — оно было бы ещё и на 18 байт короче.
 * Потому что его не понял бы релей прежней версии: он читает именно `silent` и
 * `callPush`. Молча потерянный `silent` — не мелочь: тихими едут КОПИИ веера, и
 * один присланный текст будил бы человека отдельным уведомлением с каждого
 * релея; потерянный `callPush` — звонок, который не разбудит вовсе. Такая
 * замена потребовала бы новой возможности в `hello` и переходного периода, в
 * котором утечка живёт дальше.
 *
 * Переходный период здесь не нужен вовсе — и это главный довод за цифру. Обе
 * стороны читают флаги НА ИСТИННОСТЬ (sendHeaderFlags ниже; в server/relay.js
 * это единственное место разбора), а не сравнением с `true`. Значит `0`/`1`
 * понимает каждый релей, который вообще понимает этот кадр, включая выпущенные
 * до этой правки, — а новый релей продолжает понимать `true`/`false` от
 * клиентов прежних версий. Согласовывать нечего.
 *
 * Цена — +24 байта на каждый кадр (`,"silent":0` — 11, `,"callPush":0` — 13).
 * Выигрыш ПРФ-14 на типичной реплике становится −23.8% вместо −24.6%; порог в
 * тесте (не ниже 18%) держит границу, за которой двоичный путь потерял бы смысл.
 *
 * Что по длине видно ВСЁ ЕЩЁ. Поле `ref`: у отправок, которым квитанция не
 * нужна (`queue: false` — «печатает…» и прочее эфемерное), его нет совсем, у
 * остальных оно 18 либо 22–23 символа. Это не следствие двоичного кадра —
 * прежний JSON-кадр вёл себя так же (`ref: undefined` не выводится вовсе), — и
 * закрыть это ЗДЕСЬ нельзя: метку релей возвращает в квитанции, по ней
 * снимается запись из очереди исходящих. Подставь мы постоянную строку или
 * набивку до общей ширины — квитанция перестала бы находить своё сообщение, и
 * оно осталось бы в очереди навсегда. Это отдельная работа, не эта.
 */
function buildSendHeader({
  to,
  ref,
  silent,
  callPush,
  noMeta,
  sealedVersion = SEALED_ENVELOPE_VERSION,
}) {
  const header = { type: SEND_FRAME_TYPE, version: 1, to, sv: sealedVersion };
  if (ref !== undefined && ref !== null) header.ref = ref;
  header.silent = silent ? 1 : 0;
  header.callPush = callPush ? 1 : 0;
  // ВЫС-41: «не подставляй мои метаданные снаружи». Пишется ВСЕГДА цифрой — по
  // той же причине, что silent и callPush: поле, появляющееся только при
  // истине, проступает в длине кадра и разделяет отправителей на две группы.
  header.noMeta = noMeta ? 1 : 0;
  return header;
}

/**
 * СРЕД-01: прочитать флаги кадра отправки — одно правило на обе записи.
 *
 * По проводу ходят обе сразу: клиент прежней версии присылает `true` (и только
 * при истине), нынешний — всегда цифру. Поэтому читать надо на ИСТИННОСТЬ, а не
 * сравнением с `true` или с `1`: сравнение с конкретным значением тихо
 * превратило бы одну из записей в «ложь». Цена такой тишины названа выше:
 * потерянный `silent` — уведомление с каждого релея на одно сообщение,
 * потерянный `callPush` — звонок, который не разбудит.
 *
 * Правило живёт здесь, а не в релее, по той же причине, что и весь модуль:
 * копия уезжает в server/envelopeFrame.js, и разойтись две стороны не могут.
 */
function sendHeaderFlags(header) {
  return {
    silent: !!(header && header.silent),
    callPush: !!(header && header.callPush),
    // ВЫС-41: у релея прежней версии поля нет вовсе — он подставит метаданные,
    // как раньше. Это верный запасной ход: получатель их всё равно прочтёт, а
    // сузить провод можно будет после обновления релеев.
    noMeta: !!(header && header.noMeta),
  };
}

/**
 * Заголовок кадра доставки (релей → получатель).
 *
 * Поля один в один повторяют кадр `message`, который релей собирает сейчас
 * (queuedMessageFrame в server/relay.js): идентификатор в очереди, адрес
 * устройства-отправителя и метаданные связанных устройств. Ничего нового здесь
 * не появляется — иначе двоичный переход стал бы платой приватностью за трафик.
 */
function buildMessageHeader(frame) {
  const header = {
    type: MESSAGE_FRAME_TYPE,
    version: 1,
    id: frame.id,
    sv: SEALED_ENVELOPE_VERSION,
  };
  if (frame.from) header.from = frame.from;
  if (frame.fromAccount) header.fromAccount = frame.fromAccount;
  if (frame.fromDeviceId) header.fromDeviceId = frame.fromDeviceId;
  if (frame.deviceCertificate) header.deviceCertificate = frame.deviceCertificate;
  if (frame.deviceRoster) header.deviceRoster = frame.deviceRoster;
  return header;
}

/** Собрать обратно кадр `message` из заголовка и тела. null — кадр негодный. */
function messageFromHeader(header, payload) {
  if (!header || typeof header !== 'object') return null;
  if (header.type !== MESSAGE_FRAME_TYPE || header.version !== 1) return null;
  if (typeof header.id !== 'string' || !header.id) return null;
  const envelope = sealedEnvelope(header.sv, payload);
  if (!envelope) return null;
  const message = { type: 'message', id: header.id, envelope };
  if (typeof header.from === 'string') message.from = header.from;
  if (typeof header.fromAccount === 'string') message.fromAccount = header.fromAccount;
  if (typeof header.fromDeviceId === 'string') message.fromDeviceId = header.fromDeviceId;
  if (header.deviceCertificate) message.deviceCertificate = header.deviceCertificate;
  if (header.deviceRoster) message.deviceRoster = header.deviceRoster;
  return message;
}

module.exports = {
  BINARY_ENVELOPE_CAPABILITY,
  SEND_FRAME_TYPE,
  MESSAGE_FRAME_TYPE,
  SEALED_ENVELOPE_VERSION,
  maxSealedBytes,
  sealedBytes,
  sealedEnvelope,
  buildSendHeader,
  sendHeaderFlags,
  buildMessageHeader,
  messageFromHeader,
};
