// ПРВ-1: код подключения — секрет, которого в QR нет
// ---------------------------------------------------------------------------

/**
 * Шесть случайных цифр без перекоса.
 *
 * Наивное `random % 1000000` смещено: 2^32 не делится на миллион нацело, и
 * младшие 967 296 значений выпадают чаще остальных. На шести цифрах перекос
 * ничтожен, но выписывать в коде безопасности «ничтожно смещённый» источник
 * случайности — плохая привычка: следующий, кто скопирует эту строку в место с
 * меньшим пространством, получит настоящую дыру. Отбрасываем хвост.
 *
 * `randomBytes` передаётся снаружи: на телефоне это nacl.randomBytes поверх
 * системного CSPRNG, в тестах — предсказуемый источник. Своего генератора
 * модуль не заводит, чтобы не было соблазна подменить его чем-то слабым.
 */
function generateLinkCode(randomBytes) {
  const space = 10 ** LINK_CODE_DIGITS;
  const limit = Math.floor(0x100000000 / space) * space;
  for (let attempt = 0; attempt < 64; attempt += 1) {
    const bytes = randomBytes(4);
    const value = ((bytes[0] << 24) >>> 0) + (bytes[1] << 16) + (bytes[2] << 8) + bytes[3];
    if (value < limit) return String(value % space).padStart(LINK_CODE_DIGITS, '0');
  }
  // 64 отказа подряд означают неисправный источник случайности (вероятность
  // порядка 10^-70). Продолжать с ним нельзя: код перестанет быть секретом.
  throw new Error('Источник случайности недоступен');
}

/** Ввод человека: пробелы, дефисы и прочее отбрасываем, остаются только цифры. */
function normalizeLinkCode(value) {
  const digits = String(value == null ? '' : value).replace(/\D+/g, '');
  return digits.length === LINK_CODE_DIGITS ? digits : null;
}

/** «123 456» — так код читается с экрана телефона и переносится без ошибок. */
function formatLinkCode(value) {
  const digits = normalizeLinkCode(value);
  if (!digits) return '';
  return `${digits.slice(0, 3)} ${digits.slice(3)}`;
}

function linkDigest(domain, canonical, challenge, code) {
  const digits = normalizeLinkCode(code);
  if (!digits) throw new Error('Код подключения должен состоять из шести цифр');
  if (typeof canonical !== 'string' || !canonical) throw new Error('Нет запроса привязки');
  if (typeof challenge !== 'string' || !challenge) throw new Error('Нет вызова привязки');
  const material = domain + canonical + LINK_FIELD_SEPARATOR + challenge + LINK_FIELD_SEPARATOR + digits;
  return encodeBase64(nacl.hash(decodeUTF8(material)).slice(0, 32));
}

/**
 * Доказательство компьютера телефону: «код, который ты показал, введён у меня».
 *
 * В материал входит канонизированный запрос привязки — поэтому доказательство
 * нельзя переиспользовать в другой попытке, даже если код случайно совпал, — и
 * случайный вызов телефона, поэтому его нельзя переиграть в той же попытке.
 */
function linkCodeProof(canonical, challenge, code) {
  return linkDigest(LINK_PROOF_DOMAIN, canonical, challenge, code);
}

/**
 * Встречное подтверждение телефона компьютеру, едет вместе с сертификатом.
 *
 * Нужно для того, чтобы компьютер принимал учётную запись только от телефона,
 * знающего введённый на нём код. Без этого подтверждения подтверждение привязки,
 * доставленное со стороны (телефон злоумышленника, знающий адрес компьютера из
 * его же QR), выглядело бы для компьютера так же законно, как настоящее.
 */
function linkCodeConfirmation(canonical, challenge, code) {
  return linkDigest(LINK_CONFIRM_DOMAIN, canonical, challenge, code);
}

/**
 * Сверка доказательств за время, не зависящее от числа совпавших символов.
 *
 * Здесь это скорее гигиена, чем необходимость: попыток всего три, и измерить на
 * них что-либо нельзя. Но правило «секреты сравниваются побайтово до конца»
 * должно выполняться везде, иначе однажды его нарушат там, где это важно.
 */
function linkProofsMatch(left, right) {
  if (typeof left !== 'string' || typeof right !== 'string') return false;
  if (left.length !== right.length || !left.length) return false;
  let diff = 0;
  for (let index = 0; index < left.length; index += 1) {
    diff |= left.charCodeAt(index) ^ right.charCodeAt(index);
  }
  return diff === 0;
}

module.exports = {
  STRONG_CODE_ROUNDS,
  LINK_CODE_DIGITS,
  LINK_CODE_MAX_ATTEMPTS,
  shortCode,
  strongCode,
  strongCodeAsync,
  verificationCodesMatch,
  generateLinkCode,
  normalizeLinkCode,
  formatLinkCode,
  linkCodeProof,
  linkCodeConfirmation,
  linkProofsMatch,
};
