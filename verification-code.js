'use strict';

/**
 * verification-code.js — код подтверждения привязки компьютера (АУД-КР2).
 *
 * Привязка компьютера — единственное место, где к переписке добавляется новый
 * читатель. От подмены здесь защищает ровно одно: человек сверяет код на двух
 * экранах. Значит цена ошибки в этом коде равна цене всей переписки, и правило
 * его вывода обязано жить отдельным чистым модулем с собственным тестом, а не
 * строчкой внутри восьмисотстрочного файла протокола.
 *
 * Что было не так. Код — шесть цифр, полученных из двадцати четырёх бит хеша по
 * модулю миллиона. Вычисляется мгновенно, подпись в него не входит. Значит
 * подставное устройство свободно варьирует собственный nonce и ищет совпадение
 * с кодом настоящего компьютера: замер на одном ядре в чистом JavaScript дал
 * около семнадцати тысяч вариантов в секунду и совпадение за минуту, при том что
 * QR живёт две минуты. Сверка «сравните шесть цифр» не защищала ни от чего.
 *
 * Что здесь сделано.
 *
 * Длина. К прежним шести цифрам добавлены ещё четыре, и первые шесть остались в
 * точности прежними. Поэтому сторона старой версии, показывающая короткий код, и
 * сторона новой, показывающая длинный, по-прежнему сверяемы глазами: короткий
 * является префиксом длинного. Ломать совместимость ради удлинения не пришлось.
 *
 * Цена вычисления. Добавленные цифры выводятся не одним хешем, а цепочкой из
 * STRONG_CODE_ROUNDS последовательных SHA-512. Цепочку нельзя распараллелить
 * внутри себя, поэтому одна попытка перебора стоит примерно столько же, сколько
 * честное вычисление, — порядка четверти секунды на телефоне. Подогнать все
 * десять цифр значит выполнить около 10^10 таких цепочек: недостижимо ни за
 * полторы минуты жизни QR (PAIRING_TTL_MS, ПРВ-1 — прежде было две), ни за любое
 * осмысленное время даже при распараллеливании.
 *
 * Модуль принимает УЖЕ канонизированную строку подписываемых полей, а не сам
 * запрос: канонизация живёт в протоколе (linked-devices.js), и дублировать её
 * здесь означало бы завести второй источник истины ровно там, где расхождение
 * стоит дороже всего.
 *
 * ---------------------------------------------------------------------------
 * ПРВ-1: КОД ПОДКЛЮЧЕНИЯ. Почему одного кода подтверждения оказалось мало.
 * ---------------------------------------------------------------------------
 *
 * Что было не так — и это не про длину кода, а про НАПРАВЛЕНИЕ проверки.
 *
 * Код подтверждения (`shortCode`/`strongCode` выше) выводится ДЕТЕРМИНИРОВАННО
 * из содержимого самого QR. Значит его знает каждый, у кого этот QR есть. А QR —
 * это картинка: её можно сфотографировать и прислать жертве в другом мессенджере
 * («вот, поставил себе на рабочий ноут, отсканируй, пожалуйста»). Жертва
 * сканирует, телефон считает код из QR, злоумышленник считает тот же код из того
 * же QR и называет его вслух или показывает скриншотом — цифры сходятся, потому
 * что обе стороны считали одно и то же из одного и того же входа. Экран при этом
 * убеждал: «отличается хотя бы одной цифрой — это не ваш компьютер». Ни одна
 * строка кода не проверяла, что QR показан на СВОЁМ экране, а после
 * подтверждения на чужой компьютер уезжали профиль, все контакты и вся
 * переписка, плюс право писать контактам от имени владельца.
 *
 * То есть сверка отвечала на вопрос «тот ли это QR, который я отсканировал», а
 * человек читал её как ответ на вопрос «мой ли это компьютер». Удлинение кода
 * (АУД-КР2) закрывало ПОДБОР чужого кода и не закрывало ЭТО: подбирать нечего,
 * когда правильный код и так известен обеим сторонам.
 *
 * Что сделано. Направление проверки развёрнуто. Появился ВТОРОЙ секрет — код
 * подключения, которого в QR НЕТ и вывести из QR нельзя: шесть случайных цифр,
 * которые генерирует ТЕЛЕФОН в момент сканирования и показывает на своём экране.
 * Человек вводит их на компьютере, компьютер доказывает знание кода телефону, и
 * только после этого телефон вообще начинает привязку — выдаёт сертификат,
 * публикует список устройств, отдаёт историю.
 *
 * Присланный по сети QR после этого бесполезен: у злоумышленника нет доступа к
 * экрану телефона жертвы, а значит нечего ввести на своей стороне.
 *
 * Почему доказательство — обычный хеш, без цепочки раундов, как у strongCode.
 * Цепочка нужна там, где противник может перебирать ОФЛАЙН, то есть проверять
 * догадки у себя. Здесь такого противника нет: вызов (challenge) и
 * доказательство едут между телефоном и компьютером сквозным шифрованием, и тот,
 * кто их видит, — это и есть та сторона, которая обязана знать код. Проверить
 * догадку он может только одним способом: прислать её телефону. Телефон считает
 * попытки и после LINK_CODE_MAX_ATTEMPTS неудач прекращает попытку привязки
 * целиком — требуется новый QR и новый код. Шансы угадать — три из миллиона.
 * Дорогой вывод в этих условиях не добавил бы стойкости, зато добавил бы
 * задержку на каждый ввод.
 *
 * Чего это НЕ даёт (важно не обещать лишнего):
 *   • не защищает от того, кто физически смотрит на экран телефона — он видит
 *     код так же, как видит саму переписку;
 *   • не защищает от заражённого компьютера пользователя: если ПК под контролем
 *     злоумышленника, введённый на нём код достанется ему вместе со всем
 *     остальным. Привязка защищает от ЧУЖОГО компьютера, а не от своего
 *     скомпрометированного;
 *   • не отменяет сверку отпечатка ключа: код подключения доказывает «этот QR
 *     показан на компьютере, к которому у меня есть доступ», а не «этот ключ
 *     принадлежит именно этой программе».
 */
const nacl = require('tweetnacl');
const { encodeBase64, decodeUTF8 } = require('tweetnacl-util');

const SHORT_CODE_DOMAIN = 'licno-device-verify-code-v2|';
const STRONG_CODE_DOMAIN = 'licno-device-verify-strong-v1|';
// Разные домены у двух направлений намеренно: доказательство компьютера нельзя
// переиграть как подтверждение телефона и наоборот, даже если кто-то сумеет
// развернуть кадр обратно.
const LINK_PROOF_DOMAIN = 'licno-device-link-proof-v1|';
const LINK_CONFIRM_DOMAIN = 'licno-device-link-confirm-v1|';
// Разделитель полей внутри материала хеша: без него разные разбиения одной и
// той же строки на (canonical, challenge, code) давали бы одинаковый вход.
const LINK_FIELD_SEPARATOR = '\u001f';

/** Шесть цифр: столько человек переносит с экрана на клавиатуру без ошибок. */
const LINK_CODE_DIGITS = 6;
/**
 * Три попытки. Больше не нужно: опечатку человек замечает сразу, а каждая лишняя
 * попытка — это ещё один шанс из миллиона тому, кто прислал QR по сети.
 */
const LINK_CODE_MAX_ATTEMPTS = 3;

// Компромисс между стойкостью и отзывчивостью: около 170 мс на настольном
// процессоре и порядка 0,7 с на телефоне — один раз за привязку.
const STRONG_CODE_ROUNDS = 30000;

function pairs(text) {
  const out = [];
  for (let index = 0; index < text.length; index += 2) out.push(text.slice(index, index + 2));
  return out.join(' · ');
}

/** Прежний шестизначный код. Формат и вывод не менялись — на нём совместимость. */
function shortCode(canonical) {
  const hash = nacl.hash(decodeUTF8(SHORT_CODE_DOMAIN + canonical));
  const number = (((hash[0] << 16) | (hash[1] << 8) | hash[2]) >>> 0) % 1000000;
  return pairs(String(number).padStart(6, '0'));
}

function strongSeed(canonical) {
  return nacl.hash(decodeUTF8(STRONG_CODE_DOMAIN + canonical));
}

function strongTail(digest) {
  const number = (((digest[0] << 8) | digest[1]) >>> 0) % 10000;
  return pairs(String(number).padStart(4, '0'));
}

/** Десятизначный код. Первые шесть цифр совпадают с shortCode. */
function strongCode(canonical) {
  let digest = strongSeed(canonical);
  for (let round = 1; round < STRONG_CODE_ROUNDS; round += 1) digest = nacl.hash(digest);
  return `${shortCode(canonical)} · ${strongTail(digest)}`;
}

/**
 * То же самое, но с уступкой потоку интерфейса: на телефоне цепочка занимает
 * заметное время, и заморозить на неё экран подтверждения было бы хуже, чем
 * показать его с задержкой.
 */
async function strongCodeAsync(canonical) {
  let digest = strongSeed(canonical);
  let deadline = Date.now() + 8;
  for (let round = 1; round < STRONG_CODE_ROUNDS; round += 1) {
    digest = nacl.hash(digest);
    if ((round & 255) === 0 && Date.now() >= deadline) {
      await new Promise((resolve) => setTimeout(resolve, 0));
      deadline = Date.now() + 8;
    }
  }
  return `${shortCode(canonical)} · ${strongTail(digest)}`;
}

/**
 * Сверка присланного подтверждения с локально вычисленным.
 *
 * Совместимость обеих сторон разбирается здесь, в одном месте: если пришёл
 * длинный код и он есть у нас — сверяем его целиком; если пришёл только
 * короткий (сторона прежней версии) — сверяем короткий. Подогнать длинный код
 * нельзя, короткий можно, поэтому длинный всегда в приоритете.
 */
function verificationCodesMatch(incoming, local) {
  const expectedShort = local && local.short;
  const expectedStrong = local && local.strong;
  if (incoming && incoming.strong && expectedStrong) return incoming.strong === expectedStrong;
  if (!incoming || !incoming.short || !expectedShort) return false;
  return incoming.short === expectedShort;
}

