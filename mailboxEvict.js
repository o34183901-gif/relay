/**
 * mailboxEvict.js — что выбрасывать из переполненного ящика (ВЫС-31).
 *
 * ЧТО БЫЛО НЕ ТАК
 *
 * При переполнении узел вычищал САМЫЙ СТАРЫЙ ОТРЕЗОК ЦЕЛИКОМ — шесть часов
 * записок одним движением. Рассуждение за этим стояло верное: какая записка
 * кому нужна, узел не знает и знать не должен, поэтому «выбрасывать самые
 * старые поштучно значило бы резать по живому». Беда в том, что вычистить
 * отрезок целиком — это и есть резать по живому, только шире.
 *
 * И этим можно пользоваться. Ящик открыт на запись любому, кто подключился:
 * восемь записок за кадр, шестьдесят четыре кадра в минуту. Залив ящик до
 * потолка, нападающий заставляет узел выбросить старейший отрезок — а это
 * ровно тот отрезок, за запиской из которого адресат придёт в следующий раз:
 * записка живёт два отрезка, и забирают её на втором. Свои записки при этом
 * лежат в текущем отрезке и не страдают.
 *
 * То есть: вытеснение целым отрезком делало заливку ящика прицельным оружием
 * против чужих записок, а не просто мусором.
 *
 * ЧТО ЗДЕСЬ
 *
 * Два правила, и оба — чистые числа без базы:
 *
 * 1. Убирать РОВНО столько, сколько нужно, чтобы вернуться под потолок (плюс
 *    небольшой запас, чтобы не звать уборку на каждую следующую вставку), а не
 *    «всё, что попало в отрезок».
 *
 * 2. Выбирать внутри отрезка РАВНОМЕРНО, а не по времени вставки. Это важнее
 *    первого: если выбрасывать старейшие по времени, заливающий по-прежнему
 *    выбивает чужое — он-то кладёт позже. При равномерном выборе доля
 *    выброшенного у каждого равна его доле в ящике, и заливка бьёт прежде
 *    всего по самому заливающему.
 *
 * Порядок выбора назначает УЗЕЛ при вставке (см. store.mbxPut), а не отправитель
 * и не время. Иначе нападающий, который выбирает ключи своих записок сам,
 * подобрал бы их так, чтобы под нож всегда шли чужие.
 */
'use strict';

/**
 * Запас, на который уходим ниже потолка.
 *
 * Без него уборка звалась бы на каждую вставку после переполнения: убрали одну,
 * положили одну, снова над потолком. Один процент от потолка — это тысячи
 * записок при нынешних четырёхстах тысячах, то есть уборка раз в тысячи
 * вставок, и при этом меньше трети процента ёмкости.
 */
const EVICT_HEADROOM = 0.01;

/**
 * Сколько записок убрать.
 *
 * `count` — сколько лежит сейчас, `max` — потолок. Ноль означает «ничего
 * убирать не нужно»: ящик не переполнен.
 */
function evictionSize(count, max, headroom = EVICT_HEADROOM) {
  const have = Number(count);
  const limit = Number(max);
  if (!Number.isFinite(have) || !Number.isFinite(limit) || limit <= 0) return 0;
  if (have <= limit) return 0;
  const spare = Math.max(1, Math.floor(limit * headroom));
  // Больше, чем лежит, здесь не выйдет по построению: запас — сотая доля
  // потолка, то есть он никогда не больше самого потолка, а значит
  // `have - limit + spare` не превосходит `have`. Отдельная проверка на это
  // была бы кодом, который нельзя сломать так, чтобы кто-нибудь заметил.
  return have - limit + spare;
}

module.exports = { EVICT_HEADROOM, evictionSize };
