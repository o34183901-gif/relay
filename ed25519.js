/**
 * ed25519.js — подпись и её проверка, с быстрой реализацией там, где она есть.
 *
 * ЗАЧЕМ
 *
 * Ed25519 в tweetnacl — самая дорогая операция во всём проекте. Замер на
 * настольном процессоре:
 *
 *   проверка подписи — 16,7 мс
 *   создание подписи —  7,4 мс
 *   для сравнения, X25519 —  0,67 мс, шаг храповика — 0,098 мс
 *
 * На телефоне вчетверо больше. При этом проверка подписи — не редкая операция:
 * подписанный список устройств собеседника приезжает с каждым конвертом, а
 * групповое шифрование одним ключом подписывает КАЖДОЕ сообщение (иначе участник
 * группы мог бы писать от чужого имени).
 *
 * @noble/curves делает то же самое в 5–10 раз быстрее и уже присутствует в
 * дереве зависимостей — постквантовая часть тянет @noble/hashes от того же
 * автора. Подписи полностью совместимы в обе стороны: подпись tweetnacl
 * проверяется noble и наоборот (это закреплено тестом).
 *
 * ПОЧЕМУ ОБЁРТКА, А НЕ ПРЯМАЯ ЗАМЕНА
 *
 * Замена реализации подписи в путях, где решается вопрос доверия, — не
 * оптимизация, а изменение криптографического основания. Такое не делается
 * молча. Поэтому здесь единая точка: быстрый путь используется, если библиотека
 * доступна, и tweetnacl — если нет. Переключение всех путей проверки делается
 * правкой одного места, а не пятнадцати.
 *
 * В-2: боевые пути переведены. Через этот модуль теперь идут подпись и проверка
 * QR-кода, challenge релея, подлинности релея, подписанного prekey, сертификатов
 * устройств и подписанного списка устройств — то есть всё, что проверяется на
 * КАЖДЫЙ входящий конверт. Формат подписи не изменился ни на байт: подпись
 * tweetnacl проверяется noble и наоборот, это закреплено тестом
 * (test/ed25519.test.js), поэтому клиенты разных версий совместимы в обе стороны.
 *
 * НАТ-1: у обёртки появился третий, самый быстрый уровень — OpenSSL. Он есть не
 * везде (на релее и на настольном клиенте есть, на телефоне зависит от сборки),
 * поэтому и приходит СНАРУЖИ, через `setNative`: этот файл — общее ядро, он
 * копируется и на релей, и на компьютер, и подключать здесь `node:crypto`
 * означало бы сломать сборку телефона. Кто дотянулся до OpenSSL — тот и вносит,
 * проверив его на известном векторе (src/nativeEd25519.js).
 *
 * Порядок такой: OpenSSL, если внесён; @noble/curves; tweetnacl. Формат подписи
 * у всех трёх один и тот же байт в байт — это закреплено тестом, и значит
 * уровень можно менять на ходу, не думая о совместимости.
 */

const nacl = require('tweetnacl');
// ЗАГРУЗКА @noble/curves ОТЛОЖЕНА ДО ПЕРВОЙ ПОДПИСИ ИЛИ ПРОВЕРКИ.
//
// Подключение простой формой — как в pq.js: общее ядро телефона и компьютера
// генерируется из этих файлов (scripts/sync-core.js) и понимает только её.
// Библиотека — прямая зависимость проекта и уже присутствует в дереве
// (её же тянет постквантовая часть), поэтому отдельного пути «сборка без
// @noble/curves» здесь нет. Проверка `usable` ловит другое: кривое разрешение
// модуля сборщиком, при котором импорт молча даёт undefined.
//
// Замер: загрузка @noble/curves/ed25519.js — 28,4 мс на настольной машине
// (Node 22, V8 с JIT); на телефоне работает Hermes без JIT, там дороже кратно.
// Это самая дорогая загрузка на старте — дороже постквантового ML-KEM.
//
// Платить её на КАЖДОМ запуске незачем: подпись нужна при работе с prekey, при
// привязке устройств и при проверке манифестов, а запуск обычно не делает
// ничего из этого — человек открывает существующую переписку. Библиотека
// запоминается после первой загрузки, поэтому цена платится один раз за сеанс
// и ровно тогда, когда подпись действительно понадобилась.
let nobleCache;

function nobleEd25519() {
  if (nobleCache === undefined) {
    // eslint-disable-next-line global-require
    nobleCache = require('@noble/curves/ed25519.js').ed25519;
  }
  return nobleCache;
}

function usable(implementation) {
  return implementation &&
    typeof implementation.sign === 'function' &&
    typeof implementation.verify === 'function'
    ? implementation
    : null;
}

function createEd25519(implementation) {
  // undefined означает «возьми обычную быструю реализацию» — и вот её-то мы и
  // не трогаем до первого дела. Явно переданная (в том числе null, которым
  // тесты отключают быстрый уровень) разбирается сразу: она уже в руках.
  let fastCache = implementation === undefined ? undefined : usable(implementation);

  function fast() {
    if (fastCache === undefined) fastCache = usable(nobleEd25519());
    return fastCache;
  }

  // НАТ-1: самый быстрый уровень. Вносится снаружи и только после самопроверки
  // на известном векторе — см. шапку и src/nativeEd25519.js.
  let native = null;

  /**
   * Доступна ли быстрая реализация — для диагностики и тестов.
   *
   * Вопрос задаётся по делу, поэтому здесь библиотека и загружается: ответ
   * «доступна» без загрузки был бы обещанием, а не фактом.
   */
  function fastAvailable() {
    return !!fast();
  }

  /** Внесён ли уровень OpenSSL — для диагностики и тестов. */
  function nativeAvailable() {
    return !!native;
  }

  /**
   * Внести реализацию поверх OpenSSL.
   *
   * Вызывается один раз при старте тем, кто до OpenSSL дотянулся и проверил его.
   * `null` снимает уровень обратно — это нужно тестам и это же способ откатиться,
   * не пересобирая приложение.
   *
   * Здесь сознательно НЕТ собственной проверки: она стоила бы времени на каждом
   * старте и создавала бы ложное чувство, будто внести можно что попало. Условие
   * прямое — вносит только тот, кто проверил (src/nativeEd25519.js), и это
   * стережётся отдельной проверкой связки.
   */
  function setNative(next) {
    if (next === null || next === undefined) {
      native = null;
      return false;
    }
    if (typeof next.sign !== 'function' || typeof next.verify !== 'function') {
      throw new Error('setNative: реализация обязана иметь sign и verify');
    }
    native = next;
    return true;
  }

  /**
   * Подписать. secretKey — 64-байтная секретка в формате tweetnacl (seed + public);
   * быстрой реализации нужен только seed, поэтому берём первые 32 байта.
   *
   * Уровню OpenSSL секретка передаётся целиком: он берёт из неё seed сам. На
   * результат это не влияет — обрезка дала бы тот же ключ, — но интерфейс у
   * всех трёх уровней остаётся один: «вот сообщение, вот секретка».
   */
  function sign(message, secretKey) {
    if (native) return native.sign(message, secretKey);
    const quick = fast();
    if (quick) return quick.sign(message, secretKey.subarray(0, 32));
    return nacl.sign.detached(message, secretKey);
  }

  /**
   * Проверить. Любая ошибка разбора точки или длины — это «подпись не сошлась», а
   * не исключение: значения приходят из сети, и бросать здесь означало бы отдать
   * отправителю управление потоком выполнения.
   */
  function verify(message, signature, publicKey) {
    try {
      if (native) return native.verify(message, signature, publicKey);
      const quick = fast();
      if (quick) return quick.verify(signature, message, publicKey);
      return nacl.sign.detached.verify(message, signature, publicKey);
    } catch (error) {
      return false;
    }
  }

  return { sign, verify, fastAvailable, nativeAvailable, setNative };
}

const { sign, verify, fastAvailable, nativeAvailable, setNative } = createEd25519();

module.exports = {
  sign,
  verify,
  fastAvailable,
  nativeAvailable,
  setNative,
  createEd25519,
};
