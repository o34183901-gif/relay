/**
 * mailboxEvict.test.js — сколько выбрасывать из переполненного ящика (ВЫС-31).
 *
 * Правило чистое: числа без базы. Связка с хранилищем — в mbx.test.js.
 *
 * Запуск: node server/mailboxEvict.test.js
 */
'use strict';

const assert = require('assert');

const { EVICT_HEADROOM, evictionSize } = require('./mailboxEvict');

let passed = 0;
const ok = (name) => {
  console.log('  ✓ ' + name);
  passed += 1;
};

console.log('\nВЫС-31: сколько выбрасывать из переполненного ящика\n');

// --- ящик не переполнен — не трогаем вовсе ---------------------------------

assert.strictEqual(evictionSize(0, 1000), 0, 'пустой ящик убирать не за чем');
assert.strictEqual(evictionSize(999, 1000), 0, 'под потолком — тоже');
assert.strictEqual(evictionSize(1000, 1000), 0, 'ровно потолок — это ещё не переполнение');
ok('пока ящик не переполнен, не выбрасывается ничего');

// --- переполнен: убираем лишнее плюс запас ---------------------------------

// Запас нужен, чтобы уборка не звалась на каждую следующую вставку: убрали
// одну, положили одну — и снова над потолком.
const spare = Math.max(1, Math.floor(1000 * EVICT_HEADROOM));
assert.strictEqual(evictionSize(1001, 1000), 1 + spare, 'убирается превышение плюс запас');
assert.strictEqual(evictionSize(1500, 1000), 500 + spare, 'и при большом превышении — тоже');
assert.ok(spare >= 1, 'нулевой запас означал бы уборку на каждой вставке');
ok('убирается ровно превышение плюс небольшой запас');

// Запас — доля потолка, а не постоянное число: на четырёхстах тысячах записок
// он тысячи, на тысяче — десятки, и в обоих случаях это меньше процента ёмкости.
assert.strictEqual(evictionSize(400001, 400000), 1 + 4000);
assert.ok(EVICT_HEADROOM > 0 && EVICT_HEADROOM <= 0.05, 'запас не должен съедать заметную долю ящика');
ok('запас пропорционален потолку, а не задан числом');

// --- границы ---------------------------------------------------------------

// Убрать больше, чем лежит, не выходит по построению: запас — сотая доля
// потолка, значит он никогда не больше самого потолка. Проверяем это как
// свойство, на всём диапазоне, а не одним примером: отдельной ветки в коде для
// него нет и быть не должно.
for (let limit = 1; limit <= 2000; limit += 7) {
  for (const over of [1, 2, 5, limit, limit * 3]) {
    const have = limit + over;
    assert.ok(
      evictionSize(have, limit) <= have,
      `убрать больше, чем лежит: потолок ${limit}, лежит ${have}`
    );
    assert.ok(evictionSize(have, limit) >= over, `после уборки обязано стать не больше потолка: ${limit}/${have}`);
  }
}
ok('уборка никогда не убирает больше, чем лежит, и всегда доводит до потолка');

for (const bad of [null, undefined, NaN, Infinity, 'много', {}, -5]) {
  assert.strictEqual(evictionSize(bad, 1000), 0, `негодное число записок: ${String(bad)}`);
  assert.strictEqual(evictionSize(1500, bad), 0, `негодный потолок: ${String(bad)}`);
}
ok('мусор на входе не превращается в приказ вычистить ящик');

console.log(`\nВЫС-31: ${passed} проверок пройдено`);
