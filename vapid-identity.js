/**
 * vapid-identity.js — VAPID-пара СВОЯ У КАЖДОГО УСТРОЙСТВА (ВЫС-51).
 *
 * ЧТО БЫЛО НЕ ТАК
 *
 * Web-push подписывается VAPID-парой отправителя, и push-провайдер (FCM,
 * Mozilla autopush, Apple) видит открытым текстом две вещи: публичный ключ, под
 * который выпущена подписка, и `subject` — контакт оператора из RFC 8292. У
 * «Лично» и то и другое было ОДНО НА ВЕСЬ ФЛОТ: `vapid-fleet.js` заботливо
 * раздавал одну пару всем релеям оператора, а subject был константой
 * `https://lichno.pro/`.
 *
 * Отсюда свойство, ради которого этот файл и появился. Провайдер обслуживает
 * миллионы подписок разных приложений и не знает, кто за какой стоит, — но
 * одинаковый ключ отправителя склеивает подписки в ОДНУ ГРУППУ. То есть Google
 * (или Mozilla, или Apple) в любой момент отвечает на вопрос «покажи все
 * устройства, которым пишет вот этот мессенджер»: сколько их, где они, когда их
 * будят. Содержимого пуша он не читает (тело зашифровано ключами подписки), но
 * состав и распорядок пользователей «Лично» получал даром — а это ровно те
 * метаданные, которые мессенджер обязан скрывать. Хуже того, группа была
 * ГЛОБАЛЬНОЙ: не «пользователи такого-то сервера», а «пользователи Лично»
 * целиком, потому что ключ общий у всего флота.
 *
 * ЧТО ЗДЕСЬ
 *
 * Пара выводится ДЕТЕРМИНИРОВАННО из секрета узла и адреса устройства:
 *
 *     priv = HKDF-SHA256(ikm = базовый приватный VAPID, info = метка | адрес)
 *     pub  = priv · G   (P-256, та же кривая, что и у web-push)
 *
 * Каждому устройству — свой ключ отправителя. Провайдер больше не видит группы:
 * с его стороны каждая подписка выглядит как отдельное приложение. Подписки
 * двух устройств одного человека тоже не связываются между собой.
 *
 * ПОЧЕМУ ВЫВОД, А НЕ ПРОСТО «СГЕНЕРИРОВАТЬ ПАРУ НА КАЖДОГО»
 *
 * Потому что подписку выпускает КЛИЕНТ под ключ, полученный в кадре `ready`, а
 * разбудить его потом должен ЛЮБОЙ релей флота, у которого осела очередь, — не
 * только тот, который этот ключ показал. Хранить таблицу «адрес → приватный
 * ключ» и синхронизировать её между релеями значило бы завести ещё один
 * секретный общий стейт и терять уведомления при рассинхроне. Вывод из общего
 * секрета решает это без хранения: у всех релеев флота базовый секрет один
 * (его и раздаёт vapid-fleet.js), поэтому каждый из них вычисляет для адреса
 * РОВНО ТУ ЖЕ пару и подписывает пуш ключом, который push-сервис ждёт.
 *
 * Обратная сторона названа прямо: пары всех устройств выводятся из одного
 * секрета, и владелец флота может пересчитать любую. Это не ухудшение — этот
 * же владелец и так подписывал каждый пуш общей парой. Меняется только то, что
 * видит ПОСТОРОННИЙ (push-провайдер), а он базового секрета не знает и по
 * публичному ключу его не восстановит: обратный ход — дискретный логарифм.
 *
 * ПОЧЕМУ АДРЕС УСТРОЙСТВА, А НЕ СЛУЧАЙНАЯ СОЛЬ
 *
 * Адрес получателя релей знает в обеих точках, где нужен ключ: в кадре `ready`
 * (соединение уже аутентифицировано) и при отправке пуша (`to` из очереди).
 * Случайная соль потребовала бы нового поля в протоколе и хранения — а всё, что
 * даёт соль сверх адреса, это защита от «свой же релей пересчитает ключ», чего
 * не бывает: релей и так его вычисляет по долгу службы. Чужой релей адрес знает,
 * но без базового секрета из адреса не выводится ничего.
 *
 * SUBJECT ТОЖЕ ПЕРЕСТАЁТ БЫТЬ ОБЩИМ
 *
 * Ключ на устройство ничего не даст, если рядом едет константа, по которой
 * подписки склеиваются обратно. Поэтому контактом по умолчанию становится
 * СОБСТВЕННЫЙ адрес релея: провайдер и так видит IP, с которого пришёл запрос,
 * — то есть узнаёт ровно ноль нового, — а фирменной константы, общей для всех
 * серверов оператора, больше нет. Оператор может задать свой контакт явно
 * (RELAY_VAPID_SUBJECT), как того и хочет RFC 8292.
 *
 * Модуль чистый: ни сети, ни диска, ни глобального состояния
 * (тест server/vapid-identity.test.js).
 */

'use strict';

const crypto = require('crypto');

/** Кривая web-push (RFC 8292 / RFC 8291): P-256, она же prime256v1. */
const CURVE = 'prime256v1';

/**
 * Порядок группы P-256. Приватный ключ обязан лежать в [1, n-1]: ноль не задаёт
 * точки вовсе, а значение от n и выше — это то же самое, что значение по модулю
 * n, и подсовывать такое библиотекам нельзя (одни отвергнут, другие молча
 * приведут — и релеи разойдутся в том, какой ключ считают «тем самым»).
 */
const P256_ORDER = BigInt('0xffffffff00000000ffffffffffffffffbce6faada7179e84f3b9cac2fc632551');

/** Длина приватного скаляра и несжатой точки — как их ждёт web-push. */
const SCALAR_BYTES = 32;
const PUBLIC_BYTES = 65;

/**
 * Домен вывода. Из базового секрета выводится только это и ничего больше, но
 * метка ставится всё равно: если завтра из того же секрета понадобится вывести
 * что-то ещё, одинаковые входы под разными смыслами превратятся в способ выдать
 * одну величину за другую.
 */
const DERIVE_LABEL = 'licno-vapid-device-v1';

/**
 * Сколько раз пробуем вывести скаляр, прежде чем сдаться.
 *
 * Промах (ноль или значение ≥ n) имеет вероятность порядка 2^-32 на попытку —
 * то есть на практике не случается ни разу. Цикл здесь не ради вероятности, а
 * ради определённости: без него пришлось бы либо приводить по модулю (сместив
 * распределение), либо возвращать заведомо негодный ключ.
 */
const MAX_DERIVE_ATTEMPTS = 8;

/**
 * Контакт, которым пользуемся, когда узел не знает собственного адреса.
 *
 * Такой узел не входит во флот (членство определяется по RELAY_SELF_URL) и
 * подписывает пуши СВОЕЙ базовой парой, поэтому склеивать его подписки с чужими
 * этой константе всё равно нечем. Оставлять же subject пустым нельзя: web-push
 * отвергнет отправку целиком, и уведомлений не будет вовсе.
 */
const FALLBACK_SUBJECT = 'https://lichno.pro/';

/**
 * Скаляр из байтов вывода — или null, если он вне [1, n-1].
 *
 * Отдельной функцией, потому что это единственное место, где проверяется
 * пригодность ключа: спрятанное в цикле, оно проверялось бы только тем, что
 * «вроде работает».
 */
function scalarFromBytes(bytes) {
  if (!bytes || bytes.length !== SCALAR_BYTES) return null;
  const buffer = Buffer.from(bytes);
  const value = BigInt(`0x${buffer.toString('hex')}`);
  if (value === 0n || value >= P256_ORDER) return null;
  return buffer;
}

/**
 * Пара в том виде, в каком её ждёт web-push: публичная часть — НЕСЖАТАЯ точка
 * (65 байт, первый байт 0x04), обе половины в base64url. Сжатая точка (33 байта)
 * тоже математически верна, но её не примут ни браузер в applicationServerKey,
 * ни push-сервис при сверке подписи.
 */
function keyPairFromScalar(scalar) {
  const ecdh = crypto.createECDH(CURVE);
  ecdh.setPrivateKey(scalar);
  const publicKey = ecdh.getPublicKey(null, 'uncompressed');
  if (publicKey.length !== PUBLIC_BYTES) return null;
  return { publicKey: publicKey.toString('base64url'), privateKey: scalar.toString('base64url') };
}

/**
 * VAPID-пара этого устройства.
 *
 * `basePrivateKey` — приватная половина базовой пары узла (у флота она общая,
 * у одиночного релея своя), `address` — публичный адрес устройства, тот самый,
 * которым оно авторизовалось и по которому лежит его очередь.
 *
 * Возвращает null на любом негодном входе — вызывающий тогда подписывает пуш
 * базовой парой, как и раньше. Отказ здесь не должен превращаться в «уведомлений
 * нет»: приватность важна, но не ценой доставки.
 *
 * `hkdf` подменяется в тесте: без этого ветку «вывод дал негодный скаляр»
 * невозможно пройти иначе как перебором в 2^32 попыток.
 */
function deviceVapidKeys(basePrivateKey, address, { hkdf = crypto.hkdfSync } = {}) {
  if (typeof address !== 'string' || !address) return null;
  // base64url разбирается из чего угодно и не бросает: негодный секрет виден по
  // длине, и это единственная проверка, которая здесь нужна.
  const ikm = Buffer.from(String(basePrivateKey || ''), 'base64url');
  if (ikm.length !== SCALAR_BYTES) return null;
  for (let attempt = 0; attempt < MAX_DERIVE_ATTEMPTS; attempt += 1) {
    const bytes = hkdf(
      'sha256',
      ikm,
      Buffer.from(DERIVE_LABEL, 'utf8'),
      Buffer.from(`${DERIVE_LABEL}|${attempt}|${address}`, 'utf8'),
      SCALAR_BYTES
    );
    const scalar = scalarFromBytes(Buffer.from(bytes));
    if (!scalar) continue;
    return keyPairFromScalar(scalar);
  }
  return null;
}

/** Годен ли контакт как VAPID subject: RFC 8292 разрешает https: и mailto:. */
function validSubject(value) {
  if (typeof value !== 'string' || !value || value.length > 256) return null;
  let parsed;
  try {
    parsed = new URL(value);
  } catch (error) {
    return null;
  }
  if (parsed.protocol !== 'https:' && parsed.protocol !== 'mailto:') return null;
  if (parsed.protocol === 'https:' && !parsed.hostname) return null;
  return value;
}

/**
 * Контакт для VAPID-заголовка.
 *
 * Порядок: явная настройка оператора → собственный адрес релея → прежняя
 * константа. Средняя ступень и есть смысл функции: она заменяет фирменную
 * константу, общую для всего флота, на адрес конкретного узла — который
 * провайдер и так видит по IP запроса.
 *
 * `ws://` в контакт не превращаем: обещать `https://` там, где TLS нет, — это
 * ложный контакт, и по нему оператора не найдут при злоупотреблении.
 */
function vapidSubject(selfUrl, override) {
  const explicit = validSubject(override);
  if (explicit) return explicit;
  try {
    const parsed = new URL(String(selfUrl || ''));
    if ((parsed.protocol === 'wss:' || parsed.protocol === 'https:') && parsed.hostname) {
      return `https://${parsed.host}/`;
    }
  } catch (error) {
    // Адрес узла не разобрался (не задан, задан мусором) — ниже общий запасной
    // контакт: без subject web-push не отправит ничего вообще.
  }
  return FALLBACK_SUBJECT;
}

module.exports = {
  CURVE,
  P256_ORDER,
  SCALAR_BYTES,
  PUBLIC_BYTES,
  DERIVE_LABEL,
  MAX_DERIVE_ATTEMPTS,
  FALLBACK_SUBJECT,
  scalarFromBytes,
  keyPairFromScalar,
  deviceVapidKeys,
  validSubject,
  vapidSubject,
};
